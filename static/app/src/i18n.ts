export type Key = keyof typeof en;
type Lang = 'en' | 'de';

export const useLang = create<{ lang: Lang; set: (l: Lang) => void }>((set) => ({
  lang: (navigator.language || 'en').toLowerCase().startsWith('de') ? 'de' : 'en',
  set: (lang) => set({ lang }),
}));

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s: string = (lang === 'de' ? de : en)[key] ?? en[key];
  if (vars) {
    // plural forms: "{n|item|items}" picks the singular when n is 1
    s = s.replace(/\{(\w+)\|([^|}]*)\|([^}]*)\}/g, (m, k: string, one: string, many: string) => (k in vars ? (Number(vars[k]) === 1 ? one : many) : m));
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

export function useT() {
  const lang = useLang((s) => s.lang);
  return (key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

export function formatDate(iso: string, lang: Lang) {
  return new Date(iso).toLocaleDateString(lang === 'de' ? 'de-DE' : 'en-GB', { day: '2-digit', month: '2-digit', year: 'numeric' });
}
